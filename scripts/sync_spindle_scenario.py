#!/usr/bin/env python3
"""Embed the shared Spindle 3 scenario source in the client's producer generator.

``src/iot_twin/scenario_engine/spindle_scenario.py`` is the one generator for
the live producer and the risk model's training data. The producer notebook is
rendered by the client, so this script writes the module's source, verbatim, to
``client/src/lib/generated/spindle-scenario-python.ts``.

    python scripts/sync_spindle_scenario.py          # rewrite the TS module
    python scripts/sync_spindle_scenario.py --check  # exit 1 when it is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "iot_twin" / "scenario_engine" / "spindle_scenario.py"
TARGET = ROOT / "client" / "src" / "lib" / "generated" / "spindle-scenario-python.ts"

HEADER = (
    "// GENERATED by scripts/sync_spindle_scenario.py from\n"
    "// src/iot_twin/scenario_engine/spindle_scenario.py. Do not edit by hand.\n"
    "// The producer notebook embeds this Python source verbatim, so the live\n"
    "// producer and the risk model's training data share one generator.\n"
)


def render(source: str) -> str:
    return f"{HEADER}export const SPINDLE_SCENARIO_PYTHON: string = {json.dumps(source)};\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    expected = render(SOURCE.read_text(encoding="utf-8"))
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    if args.check:
        if current != expected:
            print(f"{TARGET.relative_to(ROOT)} is stale: run scripts/sync_spindle_scenario.py")
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
